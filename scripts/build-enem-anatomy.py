#!/usr/bin/env python3
"""Validate the didactic index; generate browser data without guessing labels."""
import hashlib
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / 'enem-anatomy-data.json').read_text())
source = (ROOT / 'enem-data.json').read_bytes()
bank = {q['id']: q for q in json.loads(source)['questions']}
assert data['scope'] == {'firstYear': 2021, 'lastYear': 2025, 'application': 'regular'}
assert data['source']['bankSha256'] == hashlib.sha256(source).hexdigest(), 'Corpus changed: review before regenerating.'
expected = {q['id'] for q in bank.values() if 2021 <= q['year'] <= 2025 and q['application'] == 'regular'}
topics = {t['id']: t for t in data['topics']}
patterns = {p['id']: p for p in data['patterns']}
allowed = {'matematica': {'matematica'}, 'ciencias-natureza': {'biologia', 'fisica', 'quimica'}, 'ciencias-humanas': {'historia', 'geografia', 'filosofia', 'sociologia'}, 'linguagens': {'portugues', 'artes', 'educacao-fisica', 'ingles', 'espanhol'}}
assert len(topics) == len(data['topics']) and len(patterns) == len(data['patterns']) == 10
for t in topics.values():
    assert t['subject'] in allowed[t['area']], t
    assert all(isinstance(t[k], str) and t[k].strip() for k in ['title', 'description', 'firstStep', 'trap']), t
seen = set()
for r in data['questions']:
    assert r['id'] in expected and r['id'] not in seen, r['id']
    seen.add(r['id'])
    q = bank[r['id']]
    assert r['pattern'] in patterns and r['confidence'] in {'high', 'medium', 'low'}, r
    assert isinstance(r['command'], str) and 1 <= len(r['command']) <= 180, r
    if r['topic'] is None:
        assert r['confidence'] == 'low' and r.get('note'), r
    else:
        t = topics[r['topic']]
        assert t['area'] == q['area'], r
        assert not q.get('language') or t['subject'] == q['language'], r
assert seen == expected and len(seen) == 925
for language in ['ingles', 'espanhol']:
    qs = [bank[id_] for id_ in seen if not bank[id_].get('language') or bank[id_]['language'] == language]
    counts = Counter((q['year'], q['area']) for q in qs)
    assert len(qs) == 900 and len(counts) == 20 and set(counts.values()) == {45}, counts
(ROOT / 'enem-anatomy-data.js').write_text("'use strict';\n// Generated by scripts/build-enem-anatomy.py.\nglobalThis.FURG_ENEM_ANATOMY_DATA=" + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'PASS: 925 indexed records; 900 per language; {len(topics)} topics; 10 patterns.')
